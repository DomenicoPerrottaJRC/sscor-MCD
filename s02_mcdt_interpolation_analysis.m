%% ========================================================================
% s02_mcdt_interpolation_analysis.m
% ========================================================================
%
% INTERPOLATION ANALYSIS OF THE CALIBRATION OUTPUT
%
% Purpose:
%   Post-process the calibration results produced by
%   s01_mcdt_finite_sample_calibration.m and compare interpolation
%   strategies for the two quantities studied in the paper:
%
%     (A) Section 5.4:
%         delta_hat(n,p,alpha0,nu) = 1 / BiasDet
%
%     (B) Section 6:
%         kappa_RD^delta(n,p,nu,alpha0,conflev)
%
% Workflow:
%   1. Load the calibration CSV files.
%   2. Extract the target quantity for Section 5.4 and Section 6.
%   3. Compare interpolation methods:
%        - scattered linear interpolation
%        - two-dimensional LOESS
%        - PCHIP in n followed by linear interpolation in alpha0
%   4. Export summary tables, dense lookup tables, and diagnostic figures.
%
% Notes:
%   - Section 5.4 uses the mean-root-determinant BiasDet construction.
%   - Section 6 uses the RD calibration output from the main simulation.
%   - No extrapolation is performed; values outside the convex hull are NaN.
%   - The two analyses are saved in separate folders so their outputs
%     cannot be mixed.
%
% Main inputs:
%   - calibration_results: selects the output folder from s01
%   - deltaFile: BiasDet_table_mean_root.csv
%   - rdFile: mcd_heavytails_RD_calibration.csv
%
% Main outputs:
%   - interpolation summaries, lookup tables, and plots for delta_hat
%   - interpolation summaries, lookup tables, and plots for kappa_RD^delta
%
% Dependencies:
%   - MATLAB
%   - Statistics Toolbox
%   - files generated by s01_mcdt_finite_sample_calibration.m
%
% Full call chain:
%   s02_mcdt_interpolation_analysis.m
%       -> analyseTable
%           -> predictLinear
%           -> fitLoessSurface
%               -> evaluateLoess
%           -> evaluateDenseLoess
%               -> evaluateLoess
%           -> makeLoessLookupTable
%           -> predictPchip
%           -> curveRows
%           -> transitionRows
%       -> plotLoessInterpolants
%
% ========================================================================

clear; clc; close all   % cleaning

seed = 20260711;     % Reproducibility
projectRoot = pwd;   % Your project folder: results will be saved there

%% ========================================================================
% SIMULATION SETTINGS
% =========================================================================

% Select which calibration result folder to read from.
%   'paper_all'    -> main paper output
%   'paper_grass'  -> Grass-data variant
%    otherwise     -> user selects the folder name directly
calibration_results = 'paper_all'; 

% Section 5.4 construction to analyse.
% The mean-root version matches the main delta-hat table used in the paper.
deltaConstruction = 'mean_root';

% RD output method to analyse from the calibration database.
rdMethod = 'det_mean_root';

% LOESS smoothing span used for the interpolation fits.
loessSpan      = 0.15;

% Use every `validationStep`-th n value as a held-out point when computing
% validation errors for the interpolation comparison.
validationStep = 5;

% Dense grid used only to export the LOESS surface as a lookup table.
% Values outside the convex hull are left as NaN.
denseNGrid      = 50:1:500;
denseAlpha0Grid = 0.05:0.01:0.50;

% plot controls
producePlots   = true;
produceSurfacePlots = true;

% If empty [], plot every alpha0 surface found in the data.
% Otherwise, plot only the selected alpha0 values.
plotAlpha0Values = [0.05 0.25 0.50];


%% ========================================================================
% STORAGE AND OUTPUT FILES
% ========================================================================
%
% Add the project folders to the MATLAB path so the analysis can call the
% simulation, core, and plotting helpers.
addpath(genpath(fullfile(projectRoot, 'src_srep')));
addpath(genpath(fullfile(projectRoot, 'src_core')));
addpath(genpath(fullfile(projectRoot, 'src_plots')));

% Root folder where all replicability outputs are stored.
resultsRoot    = fullfile(projectRoot, 'REPLICABILITY_RESULTS');

% Timestamp used to create a unique output folder for a specific new run.
ts             = datestr(now, 'yyyy-mm-dd_HHMMSS');

% Select the input folder containing the results from s01.
% The output folder is always kept separate from the input data.
switch calibration_results
    case 'paper_all'
        % This is used for the current draft of the paper
        inputFolder = [resultsRoot filesep 'article' filesep 'Results_correction_alpha0extended_2026-09-27_120522/'];
        % The output root is separate from the simulation results
        outputRoot  = [resultsRoot filesep 'article' filesep 'MCDt_all_interpolation_analysis' '_' ts];
    case 'paper_grass'
        % This is used to cover the case of the Grass dataset
        inputFolder = [resultsRoot filesep 'article' filesep 'Results_correction_p3_nu8_alpha0extended_2026-10-02'];
        % The output root is separate from the simulation results
        outputRoot  = [resultsRoot filesep 'article' filesep 'MCDt_all_interpolation_analysis_p3_nu8' '_' ts];
    otherwise
        inputFolder = [resultsRoot filesep calibration_results];
        outputRoot  = fullfile(resultsRoot, ['interpolation_' ts]);
        mkdir(outputRoot);
end

% Section 5.4 input: BiasDet table produced by estimateBiasDetFactors.m.
% The delta quantity is defined as the reciprocal of BiasDet.
deltaFile = fullfile(inputFolder, 'BiasDet_table_mean_root.csv');

% Section 6 input: RD calibration database produced by s01.
rdFile = fullfile(inputFolder, 'mcd_heavytails_RD_calibration.csv');



%% ------------------------- SECTION 5.4: DELTA -------------------------
%
% Section 5.4 studies the determinant-based finite-sample factor
% delta_hat = 1 / BiasDet.
%
% This block:
%   1. loads the BiasDet calibration table produced by s01,
%   2. computes delta_hat,
%   3. adds the paper's finite-sample diagnostic quantities,
%   4. compares interpolation methods on the delta surface,
%   5. saves the raw rows, summary tables, and dense LOESS lookup table.
%

if ~isfile(deltaFile)
    error('Section 5.4 input file not found: %s', deltaFile);
end
D = readtable(deltaFile);
required = {'alpha0','n','p','nu','BiasDet'};
assert(all(ismember(required,D.Properties.VariableNames)), ...
    'The delta input must contain columns: alpha0, n, p, nu, BiasDet.');

% Finite-sample calibration factor used in Section 5.4.
D.delta_hat = 1 ./ D.BiasDet;
D.quantity = repmat({'delta_hat'},height(D),1);

% Optional finite-sample diagnostics used in the paper.
D.q_n = floor((D.n + D.p + 1) ./ 2);
D.h_n = floor(D.n - 2 .* (D.n - D.q_n) .* D.alpha0);
D.alpha_n = 1 - D.h_n ./ D.n;

% Analyse the delta surface for each (p, nu) slice.
deltaOut = fullfile(outputRoot,'delta_interpolation');
if producePlots, mkdir(fullfile(deltaOut,'plots')); end
[D,DeltaSummary] = analyseTable(D, 'delta_hat', {'p','nu'}, deltaOut, ...
    'delta', loessSpan, validationStep, plotAlpha0Values, ...
    producePlots, produceSurfacePlots, denseNGrid, denseAlpha0Grid);

% Save the dense LOESS lookup table and summary outputs.
writetable(DeltaSummary.loessLookup, fullfile(deltaOut,'delta_loess_lookup.csv'));
writetable(D, fullfile(deltaOut,'delta_analysis_rows.csv'));
writetable(DeltaSummary.surface, fullfile(deltaOut,'delta_surface_summary.csv'));
writetable(DeltaSummary.curve, fullfile(deltaOut,'delta_curve_summary.csv'));
writetable(DeltaSummary.transitions, fullfile(deltaOut,'delta_h_transitions.csv'));
save(fullfile(deltaOut,'MCDt_delta_interpolation_analysis.mat'), ...
    'D','DeltaSummary','deltaFile','deltaConstruction','loessSpan', ...
    'validationStep','plotAlpha0Values','denseNGrid','denseAlpha0Grid');

%% -------------------------- SECTION 6: RD -----------------------------
%
% Section 6 studies the calibrated robust-distance factor
% kappa_RD^delta = q_emp / q_asym.
%
% This block:
%   1. loads the RD calibration database produced by s01,
%   2. filters the rows for the chosen correction method,
%   3. adds the paper's finite-sample diagnostic quantities,
%   4. compares interpolation methods on the kappa_RD surface,
%   5. saves the raw rows, summary tables, and dense LOESS lookup table.
%

if ~isfile(rdFile)
    error('Section 6 input file not found: %s', rdFile);
end
R = readtable(rdFile);
required = {'method','n','p','nu','alpha0','conflev','kappa_RD'};
assert(all(ismember(required,R.Properties.VariableNames)), ...
    'The RD input must contain columns: method, n, p, nu, alpha0, conflev, kappa_RD.');

% Keep only the correction method selected at the top of the script.
R = R(strcmp(string(R.method),rdMethod),:);
if isempty(R)
    error('No RD rows found for method "%s".',rdMethod);
end

% Quantity label used in the exported tables and plots.
R.quantity = repmat({'kappa_RD_delta'},height(R),1);

% Same finite-sample diagnostics used in Section 5.4.
R.q_n = floor((R.n + R.p + 1) ./ 2);
R.h_n = floor(R.n - 2 .* (R.n - R.q_n) .* R.alpha0);
R.alpha_n = 1 - R.h_n ./ R.n;

% Analyse the RD surface for each (p, nu, conflev) slice.
rdOut = fullfile(outputRoot,'RD_interpolation');
if producePlots, mkdir(fullfile(rdOut,'plots')); end
[R,RDSummary] = analyseTable(R, 'kappa_RD', {'p','nu','conflev'}, rdOut, ...
    'RD', loessSpan, validationStep, plotAlpha0Values, ...
    producePlots, produceSurfacePlots, denseNGrid, denseAlpha0Grid);

% Save the dense LOESS lookup table separately from the Section 5.4 table.
writetable(RDSummary.loessLookup, fullfile(rdOut,'RD_loess_lookup.csv'));

% Keep the original RD columns plus the interpolants and residual summaries.
writetable(R, fullfile(rdOut,'RD_analysis_rows.csv'));
writetable(RDSummary.surface, fullfile(rdOut,'RD_surface_summary.csv'));
writetable(RDSummary.curve, fullfile(rdOut,'RD_curve_summary.csv'));
writetable(RDSummary.transitions, fullfile(rdOut,'RD_h_transitions.csv'));
save(fullfile(rdOut,'MCDt_RD_interpolation_analysis.mat'), ...
    'R','RDSummary','rdFile','rdMethod','loessSpan', ...
    'validationStep','plotAlpha0Values','denseNGrid','denseAlpha0Grid');

fprintf('\nFinished. Separate outputs were written to:\n  %s\n  %s\n',deltaOut,rdOut);


