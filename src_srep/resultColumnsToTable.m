    cols.emp_size_calibrated,...
    cols.sizeRatio_calibrated,...
    cols.emp_size_pooled,...
    cols.sizeRatio_calibrated_pooled,...
    cols.emp_size_replicationwise,...
    cols.sizeRatio_calibrated_replicationwise,...
    cols.biasdet_found,...
    'VariableNames',...
    {'n',...
    'p',...
    'nu',...
    'alpha0',...
    'conflev',...
    'q_asym_sq',...
    'q_emp_avgquantile_sq',...
    'q_emp_pooled_sq',...
    'kappa_RD',...
    'q_RD_calibrated_sq',...
